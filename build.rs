use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=ui/dist");
    println!("cargo:rerun-if-changed=assets/monword.ico");
    println!("cargo:rerun-if-changed=assets/monword_rgba_64.bin");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR missing"));
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR missing"));
    let ui_dist = manifest_dir.join("ui").join("dist");

    generate_embedded_assets(&ui_dist, &out_dir.join("embedded_assets.rs"));
    copy_webview2_loader(&out_dir);
    embed_windows_icon(&manifest_dir, &out_dir);
}

fn generate_embedded_assets(ui_dist: &Path, dest_rs: &Path) {
    let mut entries = Vec::<(String, PathBuf)>::new();
    if ui_dist.is_dir() {
        collect_files(ui_dist, ui_dist, &mut entries);
    }

    let mut code = String::from("// Auto-generated by build.rs\n");
    code.push_str("pub fn get_asset(raw_path: &str) -> Option<(&'static str, &'static [u8])> {\n");
    code.push_str("    let trimmed = raw_path.trim_start_matches('/');\n");
    code.push_str("    let key = if trimmed.is_empty() { \"index.html\" } else { trimmed };\n");
    code.push_str("    match key {\n");

    if entries.is_empty() {
        // Fallback when ui/dist has not been built yet (e.g., running `cargo test` early)
        code.push_str(
            "        \"index.html\" => Some((\"text/html; charset=utf-8\", b\"<!doctype html><html><body><h1>Chuan Hoa Van Ban Pro (Build UI first)</h1></body></html>\")),\n",
        );
    } else {
        for (rel, abs) in &entries {
            let mime = detect_mime(rel);
            let abs_str = abs.to_string_lossy().replace('\\', "\\\\");
            let rel_escaped = rel.replace('"', "\\\"");
            code.push_str(&format!(
                "        \"{}\" => Some((\"{}\", include_bytes!(\"{}\"))),\n",
                rel_escaped, mime, abs_str
            ));
        }
    }

    code.push_str("        _ => None,\n");
    code.push_str("    }\n");
    code.push_str("}\n");

    fs::write(dest_rs, code).expect("Failed to write embedded_assets.rs");
}

fn collect_files(root: &Path, current: &Path, out: &mut Vec<(String, PathBuf)>) {
    let Ok(rd) = fs::read_dir(current) else {
        return;
    };
    let mut items: Vec<PathBuf> = rd.filter_map(|e| e.ok().map(|x| x.path())).collect();
    items.sort();
    for path in items {
        if path.is_dir() {
            collect_files(root, &path, out);
        } else if path.is_file() {
            if let Ok(rel) = path.strip_prefix(root) {
                let rel_norm = rel.to_string_lossy().replace('\\', "/");
                out.push((rel_norm, path));
            }
        }
    }
}

fn detect_mime(rel_path: &str) -> &'static str {
    let lower = rel_path.to_ascii_lowercase();
    if lower.ends_with(".html") {
        "text/html; charset=utf-8"
    } else if lower.ends_with(".js") || lower.ends_with(".mjs") {
        "application/javascript; charset=utf-8"
    } else if lower.ends_with(".css") {
        "text/css; charset=utf-8"
    } else if lower.ends_with(".svg") {
        "image/svg+xml"
    } else if lower.ends_with(".ico") {
        "image/x-icon"
    } else if lower.ends_with(".png") {
        "image/png"
    } else if lower.ends_with(".jpg") || lower.ends_with(".jpeg") {
        "image/jpeg"
    } else if lower.ends_with(".woff2") {
        "font/woff2"
    } else if lower.ends_with(".woff") {
        "font/woff"
    } else if lower.ends_with(".json") || lower.ends_with(".webmanifest") {
        "application/json; charset=utf-8"
    } else {
        "application/octet-stream"
    }
}

fn copy_webview2_loader(out_dir: &Path) {
    // OUT_DIR is typically target/<triple>/<profile>/build/<pkg>-<hash>/out
    let Some(target_profile_dir) = out_dir
        .parent()
        .and_then(|p| p.parent())
        .and_then(|p| p.parent())
    else {
        return;
    };

    let dest_dll = target_profile_dir.join("WebView2Loader.dll");

    // Search cargo registry src for webview2-com-sys-*/x64/WebView2Loader.dll
    let cargo_home = env::var("CARGO_HOME")
        .map(PathBuf::from)
        .unwrap_or_else(|_| {
            let home = env::var("USERPROFILE").unwrap_or_else(|_| ".".to_string());
            PathBuf::from(home).join(".cargo")
        });

    let registry_src = cargo_home.join("registry").join("src");
    if let Some(found) = find_webview2_dll(&registry_src) {
        let _ = fs::copy(&found, &dest_dll);
        // Also check deps folder just in case cargo test runs binaries from deps/
        let deps_dll = target_profile_dir.join("deps").join("WebView2Loader.dll");
        if target_profile_dir.join("deps").is_dir() {
            let _ = fs::copy(&found, &deps_dll);
        }
    }
}

fn find_webview2_dll(registry_src: &Path) -> Option<PathBuf> {
    let rd = fs::read_dir(registry_src).ok()?;
    for index_entry in rd.filter_map(|e| e.ok()) {
        let index_path = index_entry.path();
        if !index_path.is_dir() {
            continue;
        }
        let Ok(crates) = fs::read_dir(&index_path) else {
            continue;
        };
        for crate_entry in crates.filter_map(|e| e.ok()) {
            let name = crate_entry.file_name();
            let name_str = name.to_string_lossy();
            if name_str.starts_with("webview2-com-sys-") {
                let candidate = crate_entry.path().join("x64").join("WebView2Loader.dll");
                if candidate.is_file() {
                    return Some(candidate);
                }
            }
        }
    }
    None
}

fn embed_windows_icon(manifest_dir: &Path, out_dir: &Path) {
    if env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("windows") {
        return;
    }

    let ico_path = manifest_dir.join("assets").join("monword.ico");
    if !ico_path.is_file() {
        return;
    }

    let Some(windres_bin) = find_windres() else {
        println!("cargo:warning=windres.exe not found; skipping EXE icon embedding");
        return;
    };

    let pkg_ver = env::var("CARGO_PKG_VERSION").unwrap_or_else(|_| "4.0.0".to_string());
    let mut ver_parts: Vec<&str> = pkg_ver.split('.').collect();
    while ver_parts.len() < 4 {
        ver_parts.push("0");
    }
    let ver_comma = ver_parts[..4].join(",");
    let rc_path = out_dir.join("monword.rc");
    let obj_path = out_dir.join("monword_res.o");
    // Forward slashes prevent RC escape-sequence issues with Windows backslashes.
    let ico_rc = ico_path.to_string_lossy().replace('\\', "/");
    let rc_content = format!(
        r#"1 ICON "{ico}"
1 VERSIONINFO
FILEVERSION {ver_comma}
PRODUCTVERSION {ver_comma}
FILEFLAGSMASK 0x3fL
FILEFLAGS 0x0L
FILEOS 0x40004L
FILETYPE 0x1L
FILESUBTYPE 0x0L
BEGIN
  BLOCK "StringFileInfo"
  BEGIN
    BLOCK "040904b0"
    BEGIN
      VALUE "CompanyName", "Mon Office Ecosystem\0"
      VALUE "FileDescription", "MonWord {pkg_ver} - Chuan Hoa Van Ban Hanh Chinh Pro\0"
      VALUE "FileVersion", "{pkg_ver}.0\0"
      VALUE "InternalName", "MonWord\0"
      VALUE "LegalCopyright", "Copyright (C) 2026 Mon Office Ecosystem. All rights reserved.\0"
      VALUE "OriginalFilename", "MonWord.exe\0"
      VALUE "ProductName", "MonWord - Chuan Hoa Van Ban Pro\0"
      VALUE "ProductVersion", "{pkg_ver}\0"
    END
  END
  BLOCK "VarFileInfo"
  BEGIN
    VALUE "Translation", 0x0409, 1200
  END
END
"#,
        ico = ico_rc,
        ver_comma = ver_comma,
        pkg_ver = pkg_ver
    );
    fs::write(&rc_path, rc_content).expect("Failed to write monword.rc");

    let status = Command::new(&windres_bin)
        .arg("-i")
        .arg(&rc_path)
        .arg("-O")
        .arg("coff")
        .arg("-o")
        .arg(&obj_path)
        .status()
        .expect("Failed to execute windres.exe");

    assert!(status.success(), "windres.exe failed to compile monword.rc");
    println!("cargo:rustc-link-arg-bins={}", obj_path.display());
}

fn find_windres() -> Option<PathBuf> {
    if Command::new("windres").arg("--version").output().is_ok() {
        return Some(PathBuf::from("windres"));
    }

    let local_app_data = env::var("LOCALAPPDATA").ok()?;
    let winget_pkgs = PathBuf::from(local_app_data).join("Microsoft").join("WinGet").join("Packages");
    let rd = fs::read_dir(winget_pkgs).ok()?;
    for entry in rd.filter_map(|e| e.ok()) {
        if entry.file_name().to_string_lossy().starts_with("BrechtSanders.WinLibs") {
            let candidate = entry.path().join("mingw64").join("bin").join("windres.exe");
            if candidate.is_file() {
                return Some(candidate);
            }
        }
    }
    None
}
